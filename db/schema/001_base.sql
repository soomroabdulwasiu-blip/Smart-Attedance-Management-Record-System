-- Each statement ends with a slash on its own line for the migration runner.
CREATE TABLE roles (
 role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_name VARCHAR2(30) NOT NULL UNIQUE
)
/
CREATE TABLE departments (
 dept_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dept_name VARCHAR2(200) NOT NULL UNIQUE, dept_code VARCHAR2(30) UNIQUE
)
/
CREATE TABLE users (
 user_id VARCHAR2(36) PRIMARY KEY, full_name VARCHAR2(200) NOT NULL,
 email VARCHAR2(255) NOT NULL UNIQUE, password_hash VARCHAR2(255) NOT NULL,
 role_id NUMBER NOT NULL REFERENCES roles(role_id), department VARCHAR2(200),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)
/
CREATE TABLE students (
 student_id VARCHAR2(36) PRIMARY KEY, roll_number VARCHAR2(64) NOT NULL UNIQUE,
 full_name VARCHAR2(200) NOT NULL, email VARCHAR2(255), phone VARCHAR2(40),
 dept_id NUMBER NOT NULL REFERENCES departments(dept_id),
 semester NUMBER DEFAULT 1 NOT NULL CHECK (semester BETWEEN 1 AND 16),
 batch_year NUMBER(4) NOT NULL, is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 face_enrolled NUMBER(1) DEFAULT 0 NOT NULL CHECK (face_enrolled IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)
/
CREATE TABLE student_logins (
 login_id VARCHAR2(36) PRIMARY KEY,
 student_id VARCHAR2(36) NOT NULL UNIQUE REFERENCES students(student_id) ON DELETE CASCADE,
 email VARCHAR2(255) NOT NULL UNIQUE, password_hash VARCHAR2(255) NOT NULL,
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)
/
CREATE TABLE courses (
 course_id VARCHAR2(36) PRIMARY KEY, course_code VARCHAR2(64) NOT NULL UNIQUE,
 course_name VARCHAR2(255) NOT NULL, credit_hours NUMBER DEFAULT 3 NOT NULL,
 dept_id NUMBER NOT NULL REFERENCES departments(dept_id),
 teacher_id VARCHAR2(36) NOT NULL REFERENCES users(user_id),
 semester NUMBER DEFAULT 1 NOT NULL,
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)
/
CREATE TABLE course_enrollments (
 enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id VARCHAR2(36) NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
 student_id VARCHAR2(36) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
 enrolled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_enrollment_pair UNIQUE (course_id,student_id)
)
/
CREATE TABLE attendance (
 attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id VARCHAR2(36) NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
 student_id VARCHAR2(36) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
 teacher_id VARCHAR2(36) NOT NULL REFERENCES users(user_id),
 session_date DATE NOT NULL,
 status VARCHAR2(10) NOT NULL CHECK (status IN ('PRESENT','ABSENT','LATE')),
 check_in_method VARCHAR2(10) NOT NULL CHECK (check_in_method IN ('MANUAL','QR','FACE')),
 face_match_score NUMBER, remarks VARCHAR2(1000),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_attendance_day UNIQUE (course_id,student_id,session_date)
)
/
CREATE TRIGGER trg_attendance_updated BEFORE UPDATE ON attendance
FOR EACH ROW
BEGIN
 :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/
CREATE TABLE checkin_sessions (
 session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_token VARCHAR2(255) NOT NULL UNIQUE,
 course_id VARCHAR2(36) NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
 session_date DATE NOT NULL, teacher_id VARCHAR2(36) NOT NULL REFERENCES users(user_id),
 expires_at TIMESTAMP NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)
/
CREATE TABLE password_reset_requests (
 request_id VARCHAR2(36) PRIMARY KEY, user_type VARCHAR2(10) NOT NULL,
 user_id VARCHAR2(36) NOT NULL, user_email VARCHAR2(255) NOT NULL,
 user_name VARCHAR2(200) NOT NULL, new_password_hash VARCHAR2(255) NOT NULL,
 status VARCHAR2(16) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, resolved_at TIMESTAMP
)
/
CREATE INDEX ix_students_department ON students(dept_id,semester,is_active)
/
CREATE INDEX ix_enrollment_student ON course_enrollments(student_id)
/
CREATE INDEX ix_attendance_student ON attendance(student_id,session_date)
/
CREATE INDEX ix_courses_teacher ON courses(teacher_id,is_active)
/
CREATE VIEW vw_attendance_summary AS
 SELECT course_id,student_id,COUNT(*) total_sessions,
 SUM(CASE WHEN status='PRESENT' THEN 1 ELSE 0 END) present_count,
 SUM(CASE WHEN status='ABSENT' THEN 1 ELSE 0 END) absent_count,
 SUM(CASE WHEN status='LATE' THEN 1 ELSE 0 END) late_count,
 ROUND(100*SUM(CASE WHEN status IN ('PRESENT','LATE') THEN 1 ELSE 0 END)/COUNT(*),2) attendance_pct
 FROM attendance GROUP BY course_id,student_id
